function setLanguage(lang) {
  localStorage.setItem('language', lang);

  // Update all elements with data-lang
  document.querySelectorAll('[data-lang]').forEach(el => {
    const key = el.dataset.lang;
    if (translations[lang] && translations[lang][key]) {
      if (el.tagName === "TITLE") {
        document.title = translations[lang][key];
      } else {
        el.innerHTML = translations[lang][key]; // innerHTML for <br> and <strong>
      }
    }
  });

 // Updates for planet pages
if (document.getElementById('planetInfo') && window.location.pathname.includes('planet.html')) {
  const currentLang = lang;
  const planetName = window.currentPlanetName || "Unknown";

  // Check if planet.js has already been downloaded and if infos is present
  if (typeof infos !== 'undefined' && infos[currentLang] && infos[currentLang][planetName]) {
    document.getElementById("planetInfo").innerHTML = infos[currentLang][planetName];
  } else if (typeof infos !== 'undefined' && infos['en'] && infos['en'][planetName]) {
    document.getElementById("planetInfo").innerHTML = infos['en'][planetName]; // fallback to English
  
  }
}
  // Signal for script.js (update planet labels on the main page)
  window.dispatchEvent(new Event('languageChanged'));
}

// Automatically load the saved language when the page starts
document.addEventListener("DOMContentLoaded", () => {
  const savedLang = localStorage.getItem('language') || 'en';
  setLanguage(savedLang);
});